class I18nManager {
  constructor() {
    this.lang = localStorage.getItem('resellbd-lang') || 'en';
    document.documentElement.lang = this.lang;
  }

  get currentLang() {
    return this.lang;
  }

  t(key) {
    return TRANSLATIONS[this.lang]?.[key] || TRANSLATIONS.en?.[key] || key;
  }

  setLang(newLang) {
    this.lang = newLang;
    localStorage.setItem('resellbd-lang', newLang);
    document.documentElement.lang = newLang;
    this.updateDOM();
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: newLang } }));
  }

  toggle() {
    this.setLang(this.lang === 'en' ? 'bn' : 'en');
  }

  updateDOM() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.setAttribute('placeholder', this.t(key));
      }
    });

    // Update any language toggle buttons on page
    document.querySelectorAll('.lang-toggle-btn').forEach((btn) => {
      btn.innerHTML = `<span style="display:inline-flex;align-items:center;gap:4px;">🌐 <strong>${this.lang === 'en' ? 'EN' : 'বাং'}</strong></span>`;
    });
  }
}

export const i18n = new I18nManager();
