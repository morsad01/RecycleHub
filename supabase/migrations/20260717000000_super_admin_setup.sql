-- 2. ENHANCE IS_ADMIN() HELPER TO INCLUDE SUPER ADMIN
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND (role = 'admin' OR role = 'super_admin')
  );
$$;

-- 2.b FIX BROKEN LOG_AUDIT_EVENT() TRIGGER FUNCTION
-- Safely extracts row ID using JSONB keys for tables lacking a primary 'id' column.
CREATE OR REPLACE FUNCTION public.log_audit_event()
RETURNS trigger AS $$
DECLARE
  v_user_id uuid;
  v_old_data jsonb := null;
  v_new_data jsonb := null;
  v_record_id text := null;
BEGIN
  v_user_id := auth.uid();
  
  IF TG_OP = 'DELETE' THEN
    v_old_data := to_jsonb(OLD);
    v_record_id := COALESCE(
      v_old_data->>'id',
      v_old_data->>'key',
      v_old_data->>'name',
      (v_old_data->>'user_id') || ':' || (v_old_data->>'role_id'),
      'unknown'
    );
  ELSIF TG_OP = 'UPDATE' THEN
    v_old_data := to_jsonb(OLD);
    v_new_data := to_jsonb(NEW);
    v_record_id := COALESCE(
      v_new_data->>'id',
      v_new_data->>'key',
      v_new_data->>'name',
      (v_new_data->>'user_id') || ':' || (v_new_data->>'role_id'),
      'unknown'
    );
  ELSIF TG_OP = 'INSERT' THEN
    v_new_data := to_jsonb(NEW);
    v_record_id := COALESCE(
      v_new_data->>'id',
      v_new_data->>'key',
      v_new_data->>'name',
      (v_new_data->>'user_id') || ':' || (v_new_data->>'role_id'),
      'unknown'
    );
  END IF;

  INSERT INTO public.audit_logs (user_id, action, table_name, record_id, old_data, new_data)
  VALUES (v_user_id, TG_OP, TG_TABLE_NAME, v_record_id, v_old_data, v_new_data);
  
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  ELSE
    RETURN NEW;
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


