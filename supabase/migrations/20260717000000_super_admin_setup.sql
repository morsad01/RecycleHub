-- 4. SUPER ADMIN HELPER FUNCTION
CREATE OR REPLACE FUNCTION public.is_super_admin_check()
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'super_admin'
  ) OR EXISTS (
    SELECT 1 FROM public.user_roles ur
    JOIN public.app_roles r ON ur.role_id = r.id
    WHERE ur.user_id = auth.uid() AND r.name = 'super_admin'
  );
END;
$$;

-- 5. SECURE ADMIN USER CREATION FUNCTION (Bypasses signUp sign-in replacement)
CREATE OR REPLACE FUNCTION public.admin_create_user(
  user_email text,
  user_password text,
  user_full_name text,
  user_role text
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  new_user_id uuid;
BEGIN
  -- Security check: Only Super Admin can invoke
  IF NOT public.is_super_admin_check() THEN
    RAISE EXCEPTION 'Access Denied: Only Super Admins can create administrative users.';
  END IF;

  -- Create record in auth.users
  INSERT INTO auth.users (
    instance_id,
    email,
    encrypted_password,
    email_confirmed_at,
    raw_user_meta_data,
    role,
    aud,
    created_at,
    updated_at
  )
  VALUES (
    '00000000-0000-0000-0000-000000000000',
    user_email,
    extensions.crypt(user_password, extensions.gen_salt('bf')),
    now(),
    jsonb_build_object('full_name', user_full_name),
    'authenticated',
    'authenticated',
    now(),
    now()
  )
  RETURNING id INTO new_user_id;

  -- Update default profile role generated by handle_new_user trigger
  UPDATE public.profiles
  SET role = user_role, full_name = user_full_name
  WHERE id = new_user_id;

  -- Insert into app_roles RBAC table
  INSERT INTO public.user_roles (user_id, role_id)
  SELECT new_user_id, id FROM public.app_roles WHERE name = user_role
  ON CONFLICT DO NOTHING;

  RETURN new_user_id;
END;
$$;

-- 6. SECURE ADMIN USER DELETION FUNCTION (Cascades to profiles and data)
CREATE OR REPLACE FUNCTION public.admin_delete_user(target_user_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- Security check: Only Super Admin can invoke
  IF NOT public.is_super_admin_check() THEN
    RAISE EXCEPTION 'Access Denied: Only Super Admins can delete users.';
  END IF;

  -- Self-deletion guard
  IF auth.uid() = target_user_id THEN
    RAISE EXCEPTION 'Operation Denied: You cannot delete your own account.';
  END IF;

  -- Delete from auth.users (which cascades to profiles and other dependencies)
  DELETE FROM auth.users WHERE id = target_user_id;
END;
$$;

-- 7. SECURE ADMIN USER PASSWORD RESET
CREATE OR REPLACE FUNCTION public.admin_reset_password(target_user_id uuid, new_password text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- Security check: Only Super Admin can invoke
  IF NOT public.is_super_admin_check() THEN
    RAISE EXCEPTION 'Access Denied: Only Super Admins can reset user passwords.';
  END IF;

  -- Update user password in auth.users
  UPDATE auth.users
  SET encrypted_password = extensions.crypt(new_password, extensions.gen_salt('bf')),
      updated_at = now()
  WHERE id = target_user_id;
END;
$$;

