-- 12. DATABASE CONSOLE METRICS RPC
CREATE OR REPLACE FUNCTION public.get_database_table_stats()
RETURNS TABLE(table_name text, row_count bigint, size_pretty text)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  r record;
  r_count bigint;
BEGIN
  -- Security check: Only Super Admin can invoke
  IF NOT public.is_super_admin_check() THEN
    RAISE EXCEPTION 'Access Denied: Only Super Admins can inspect database status.';
  END IF;

  FOR r IN 
    SELECT t.table_name::text as t_name
    FROM information_schema.tables t
    WHERE t.table_schema = 'public' AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format('SELECT count(*) FROM public.%I', r.t_name) INTO r_count;
    table_name := r.t_name;
    row_count := r_count;
    size_pretty := pg_size_pretty(pg_total_relation_size('public.' || r.t_name))::text;
    RETURN NEXT;
  END LOOP;
END;
$$;



